"""Canonical data loading for the DREAM olfaction task.

This module owns the data contract of Subchallenge 1 and 2. ``prepare_graph_data`` gives a model everything
it trains and is scored on:

* molecules and their features: the tables of ``ds-build`` (SMILES, Dragon, RDKit, charges, Morgan bits,
  the published EPI Suite, name and similarity features) and PubChem's 3D structures
* the targets, read from the raw DREAM rating files exactly as the challenge scores them
* the split of ``ds-build`` (``split.csv``), which holds the official DREAM test molecules out
* the scalers of ``ds-build``, fitted on training molecules only

Every one of these is read from a file that its own command wrote, and checked, so a stale file stops
the run and never changes what a model trains on."""

